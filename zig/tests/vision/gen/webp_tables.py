# Writes zig/src/vision/vp8_tables.zig: the constant tables of the VP8 / VP8L formats (RFC 6386 and the WebP
# lossless specification), read from libwebp 1.6.0's data section and checked against known anchors.
import struct, sys
d = open("/usr/local/lib/python3.12/dist-packages/pillow.libs/libwebp-bac0fc6b.so.7.2.0", "rb").read()
def at(pat):
    i = d.find(pat); assert i >= 0 and d.find(pat, i + 1) > i or True
    return i
coeffs = d.find(bytes([128]) * 33 + bytes([253, 136, 254, 255, 228, 219, 128, 128, 128, 128, 128]))
update = d.find(bytes([255]) * 33 + bytes([176, 246, 255, 255, 255, 255, 255, 255, 255, 255, 255]))
bmodes = d.find(bytes([231, 120, 48, 89, 115, 113, 120, 152, 112]))
dc = d.find(bytes([4,5,6,7,8,9,10,10,11,12,13,14,15,16,17,17,18,19,20,20,21,21,22,22,23,23,24,25,25,26,27,28]))
plane = d.find(bytes([0x18, 0x07, 0x17, 0x19, 0x28, 0x06, 0x27, 0x29]))
ac = struct.unpack("<128H", d[dc + 128:dc + 128 + 256])
assert ac[0] == 4 and ac[127] == 284
def arr(name, typ, vals, per=16):
    lines = [f"pub const {name} = [{len(vals)}]{typ}{{"]
    for i in range(0, len(vals), per):
        lines.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    lines.append("};")
    return "\n".join(lines)
out = ["//! Constant tables of VP8 (RFC 6386) and VP8L; generated by zig/tests/vision/gen/webp_tables.py.", ""]
out.append("/// Default token probabilities [type 4][band 8][ctx 3][11], flattened.")
out.append(arr("coeffs_proba0", "u8", list(d[coeffs:coeffs + 1056]), 11))
out.append("/// Token probability update probabilities, same layout.")
out.append(arr("coeffs_update_proba", "u8", list(d[update:update + 1056]), 11))
out.append("/// Key frame sub-block mode probabilities [top 10][left 10][9], flattened.")
out.append(arr("bmodes_proba", "u8", list(d[bmodes:bmodes + 900]), 9))
out.append(arr("dc_table", "u16", list(d[dc:dc + 128])))
out.append(arr("ac_table", "u16", list(ac)))
out.append("/// VP8L: distance map codes 1..120 as (yoffset << 4) | (8 - xoffset).")
out.append(arr("code_to_plane", "u8", list(d[plane:plane + 120])))
open("/zsrc/vp8_tables.zig", "w").write("\n".join(out) + "\n")
print("ok", coeffs, update, bmodes, dc, plane)
